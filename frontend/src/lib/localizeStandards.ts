const STATIC_TRANSLATIONS: Record<string, { hi: StandardLocalization; ta: StandardLocalization }> = {
  ...(standardsData as any),
  ...EXTRA_TRANSLATIONS
};

// Also index without suffix and with alternative keys
for (const [key, val] of Object.entries(EXTRA_TRANSLATIONS)) {
  const base = key.split(":")[0].trim();
  if (!STATIC_TRANSLATIONS[base]) {
    STATIC_TRANSLATIONS[base] = val;
  }
}

export function localizeStandard(
  standardNumber: string,
  rawTitle: string,
  rawScope: string | undefined,
  rawDivision: string,
  language: string
): { title: string; scope: string; division: string; number?: string } {
  if (language !== "hi" && language !== "ta") {
    return {
      title: rawTitle,
      scope: rawScope || "",
      division: rawDivision,
      number: standardNumber,
    };
  }

  const lang = language as "hi" | "ta";
  const numTrim = (standardNumber || "").trim();
  const baseNum = numTrim.split(":")[0].trim();

  const found =
    STATIC_TRANSLATIONS[numTrim] ||
    STATIC_TRANSLATIONS[baseNum] ||
    STATIC_TRANSLATIONS[standardNumber] ||
    STATIC_TRANSLATIONS[rawTitle] ||
    (numTrim.includes("BIS Act") ? STATIC_TRANSLATIONS["BIS Act 2016"] : undefined) ||
    (numTrim.includes("QCO") || (rawTitle && rawTitle.includes("Quality Control Orders")) ? STATIC_TRANSLATIONS["QCO Framework"] : undefined) ||
    (numTrim.includes("Scheme-I") || (rawTitle && rawTitle.includes("Scheme-I")) ? STATIC_TRANSLATIONS["Scheme-I (ISI Mark)"] : undefined);

  let title = rawTitle;
  let scope = rawScope || "";
  let division = rawDivision;
  let number = standardNumber;

  if (found && found[lang]) {
    if (found[lang].title) title = found[lang].title;
    if (found[lang].scope) scope = found[lang].scope;
    if (found[lang].division) division = found[lang].division;
    if (found[lang].number) number = found[lang].number;
  }

  // Fallback division translation if division remained in English
  if (DIVISION_FALLBACKS[division]?.[lang]) {
    division = DIVISION_FALLBACKS[division][lang];
  } else if (DIVISION_FALLBACKS[rawDivision]?.[lang]) {
    division = DIVISION_FALLBACKS[rawDivision][lang];
  }

  return { title, scope, division, number };
}
